#!/usr/bin/env bash
# Prepare an Authelia instance that signs the owner in to dsh web
# (README: "Optional: sign in with Authelia").
#
#   scripts/authelia-setup.sh [--rotate-secrets] [--reset-user] <dir>
#
# Creates, under <dir>:
#   config/configuration.yml  copy of config/authelia/configuration.yml
#   config/users.yml          the single owner (argon2id hash), prompted for
#   secrets/*                 session, storage, OIDC HMAC/JWK, reset JWT and
#                             the dsh client secret (+ its pbkdf2 digest)
#   data/                     Authelia's SQLite database and notification file
#
# Every secret is generated by Authelia's own `authelia crypto` commands,
# run from the pinned image of compose.authelia.yaml (or from a local
# `authelia` binary when AUTHELIA_BIN is set). Nothing secret is printed.
# Existing secrets and users are kept unless --rotate-secrets / --reset-user.
# Run it as the user that will own the files (the container's user).
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
rotate=0
reset_user=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --rotate-secrets) rotate=1; shift ;;
    --reset-user) reset_user=1; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    -*) echo "unknown option: $1" >&2; exit 2 ;;
    *) break ;;
  esac
done
[[ $# -eq 1 ]] || { echo "usage: $0 [--rotate-secrets] [--reset-user] <dir>" >&2; exit 2; }
dir="$1"
umask 077
mkdir -p "${dir}/config" "${dir}/data" "${dir}/secrets"
dir="$(cd "${dir}" && pwd)"

# Authelia's SQLite store fails its startup check on Unraid's shfs (/mnt/user):
# keep the database on a real filesystem (compose.authelia.yaml mounts
# DSH_AUTH_DATA_DIR separately).
if [[ "${dir}" == /mnt/user/* ]]; then
  echo "warning: ${dir} is on Unraid's shfs (FUSE, where Authelia's SQLite store fails its" >&2
  echo "         startup check). Keep config/ and secrets/ here if you like, but set" >&2
  echo "         DSH_AUTH_DATA_DIR=/mnt/cache/appdata/authelia/data in .env." >&2
fi

# The Authelia image pinned in compose.authelia.yaml (Renovate bumps it there).
image="$(sed -n 's/^ *image: *\(docker\.io\/authelia\/authelia:[^ ]*\).*/\1/p' "${here}/compose.authelia.yaml" | head -n1)"
authelia() {
  if [[ -n "${AUTHELIA_BIN:-}" ]]; then
    (cd "${dir}/secrets" && "${AUTHELIA_BIN}" "$@")
  else
    [[ -n "${image}" ]] || { echo "no authelia image found in compose.authelia.yaml" >&2; exit 1; }
    docker run --rm --network none --user "$(id -u):$(id -g)" \
      --volume "${dir}/secrets:/work" --workdir /work "${image}" authelia "$@"
  fi
}

secret_names=(
  authelia_session_secret
  authelia_storage_encryption_key
  authelia_oidc_hmac_secret
  authelia_reset_password_jwt_secret
  dsh_oidc_client_secret
)
missing=()
for name in "${secret_names[@]}"; do
  if (( rotate )) || [[ ! -s "${dir}/secrets/${name}" ]]; then
    rm -f "${dir}/secrets/${name}"
    missing+=("${name}")
  fi
done
if (( ${#missing[@]} )); then
  authelia crypto rand --length 64 --charset alphanumeric --file "$(IFS=,; echo "${missing[*]}")" >/dev/null
  echo "generated: ${missing[*]}"
fi
if (( rotate )) || [[ ! -s "${dir}/secrets/authelia_oidc_jwk.pem" ]]; then
  rm -f "${dir}/secrets/authelia_oidc_jwk.pem" "${dir}/secrets/authelia_oidc_jwk.pub.pem"
  authelia crypto pair rsa generate --bits 4096 --directory . \
    --file.private-key authelia_oidc_jwk.pem --file.public-key authelia_oidc_jwk.pub.pem >/dev/null
  echo "generated: OIDC signing key (RSA 4096)"
fi
digest="${dir}/secrets/dsh_oidc_client_secret.digest"
if [[ ! -s "${digest}" || "${dir}/secrets/dsh_oidc_client_secret" -nt "${digest}" ]]; then
  # Authelia stores only a digest of the client secret; dsh gets the plaintext.
  authelia crypto hash generate pbkdf2 --variant sha512 --no-confirm \
    --password "$(cat "${dir}/secrets/dsh_oidc_client_secret")" \
    | sed -n 's/^Digest: //p' > "${digest}"
  [[ -s "${digest}" ]] || { echo "could not hash the dsh client secret" >&2; exit 1; }
  echo "generated: dsh client secret digest"
fi

cp "${here}/config/authelia/configuration.yml" "${dir}/config/configuration.yml"
chmod 0600 "${dir}/config/configuration.yml"

users="${dir}/config/users.yml"
if (( reset_user )) || [[ ! -s "${users}" ]]; then
  echo
  echo "The single account allowed to sign in to dsh."
  read -r -p "Username (letters, digits, - _ .): " username
  [[ "${username}" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "invalid username" >&2; exit 1; }
  read -r -p "E-mail (you log in with it): " email
  [[ "${email}" =~ ^[^@[:space:]]+@[^@[:space:]]+$ ]] || { echo "invalid e-mail" >&2; exit 1; }
  read -r -p "Display name: " display
  [[ -n "${display}" && "${display}" != *"'"* ]] || { echo "invalid display name" >&2; exit 1; }
  while :; do
    read -r -s -p "Password (16+ characters): " password; echo
    read -r -s -p "Password again: " again; echo
    if [[ "${password}" != "${again}" ]]; then echo "passwords differ"; continue; fi
    if (( ${#password} < 16 )); then echo "too short"; continue; fi
    break
  done
  hash="$(authelia crypto hash generate argon2 --variant argon2id --no-confirm --password "${password}" \
    | sed -n 's/^Digest: //p')"
  unset password again
  [[ -n "${hash}" ]] || { echo "could not hash the password" >&2; exit 1; }
  cat > "${users}" <<EOF
# The only account. Edit on the host; Authelia has no sign-up page.
users:
  ${username}:
    disabled: false
    displayname: '${display}'
    email: '${email,,}'
    password: '${hash}'
    groups: []
EOF
  chmod 0600 "${users}"
  echo
  echo "Set in your .env (see .env.authelia.example):"
  echo "  DSH_AUTH_OWNER=${username}"
  echo "  DSH_OIDC_ALLOWED_EMAILS=${email,,}"
fi

if [[ "$(id -u)" == 0 ]]; then
  echo
  echo "You ran this as root; the container runs as 99:100 on Unraid. Give it the files:"
  echo "  chown -R 99:100 ${dir}"
fi

echo
echo "Done. Next: fill .env from .env.authelia.example, publish Authelia over HTTPS, then"
echo "  docker compose -f compose.yaml -f compose.authelia.yaml up -d"
echo "First sign-in: register a second factor; the verification code Authelia"
echo "'e-mails' is written to ${dir}/data/notification.txt"
